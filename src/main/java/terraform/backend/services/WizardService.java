    // -----------------------------
    // TRANSPORT processing (batch of IMPORTs)
    // -----------------------------

    private void processTransport(ObjectSelection sel) {
        if (sel.getArtefacts() == null || sel.getArtefacts().isEmpty()) {
            logs.add("Transport selection has no artefacts.");
            return;
        }

        for (TransportArtefact art : sel.getArtefacts()) {
            String type = art.getType();
            String name = art.getName();
            String zip = art.getZipFileName(); // e.g. "WelcomeTemplate.zip"

            String normalizedType = type.trim().toLowerCase();
            String moduleName = "saviynt_transport_" + normalizedType;
            String modulePath = "modules/" + moduleName + "/";

            String tfContent = generateImportResource(type, name, zip);
            generatedFiles.put(modulePath + name + ".tf", tfContent);

            generatedFiles.putIfAbsent(modulePath + "variables.tf", moduleVariablesTf());
            generatedFiles.putIfAbsent(modulePath + "outputs.tf", moduleOutputsTf());
            generatedFiles.putIfAbsent(modulePath + "providers.tf", moduleProvidersTf());

            logs.add("Transport artefact processed: type=" + type + ", name=" + name + ", zip=" + zip);
        }
    }

    // -----------------------------
    // Main generation logic
    // -----------------------------

    public void generate() {
        logs.add("Starting Terraform generation...");

        generatedFiles.clear();

        // Root-level files
        generatedFiles.put("variables.tf", rootVariablesTf());
        generatedFiles.put("outputs.tf", rootOutputsTf());
        generatedFiles.put("provider.tf", rootProviderTf());

        // Build main.tf
        StringBuilder mainTf = new StringBuilder();

        // STANDARD / EXPORT / IMPORT modules
        for (ObjectSelection sel : selections) {
            String op = sel.getOperation() == null ? "STANDARD" : sel.getOperation().toUpperCase();
            if ("TRANSPORT".equals(op)) {
                continue;
            }

            String type = sel.getType();
            String normalized = normalize(type);
            String moduleName = "saviynt_" + normalized;

            mainTf.append("""
                module "%s" {
                  source = "./modules/%s"

                  environment    = var.environment
                  workspace_name = var.workspace_name
                  module_enabled = true

                  providers = {
                    saviynt = saviynt
                  }
                }

                """.formatted(moduleName, moduleName));
        }

        // TRANSPORT modules
        for (ObjectSelection sel : selections) {
            String op = sel.getOperation() == null ? "STANDARD" : sel.getOperation().toUpperCase();
            if (!"TRANSPORT".equals(op)) continue;
            if (sel.getArtefacts() == null) continue;

            for (TransportArtefact art : sel.getArtefacts()) {
                String type = art.getType();
                String normalizedType = type.trim().toLowerCase();
                String moduleName = "saviynt_transport_" + normalizedType;

                mainTf.append("""
                    module "%s" {
                      source = "./modules/%s"

                      environment    = var.environment
                      workspace_name = var.workspace_name
                      module_enabled = true

                      providers = {
                        saviynt = saviynt
                      }
                    }

                    """.formatted(moduleName, moduleName));
            }
        }

        generatedFiles.put("main.tf", mainTf.toString());

        // Generate module files for STANDARD / EXPORT / IMPORT
        for (ObjectSelection sel : selections) {
            String op = sel.getOperation() == null ? "STANDARD" : sel.getOperation().toUpperCase();

            if ("TRANSPORT".equals(op)) {
                processTransport(sel);
                continue;
            }

            String type = sel.getType();
            String name = sel.getName();
            Map<String, String> attrs = sel.getAttributes();

            String normalized = normalize(type);
            String moduleName = "saviynt_" + normalized;
            String modulePath = "modules/" + moduleName + "/";

            generatedFiles.putIfAbsent(modulePath + "variables.tf", moduleVariablesTf());
            generatedFiles.putIfAbsent(modulePath + "outputs.tf", moduleOutputsTf());
            generatedFiles.putIfAbsent(modulePath + "providers.tf", moduleProvidersTf());

            String tfContent;
            switch (op) {
    case "EXPORT":
        String zipNameExport = name + ".zip";
        tfContent = generateExportResource(type, name, zipNameExport);
        break;

    case "IMPORT":
        String zipNameImport = sel.getZipFileName() != null
                ? sel.getZipFileName()
                : name + ".zip";
        tfContent = generateImportResource(type, name, zipNameImport);
        break;

    case "STANDARD":
    default:
        tfContent = generateStandardResource(type, name, attrs);
        break;
}

            generatedFiles.put(modulePath + name + ".tf", tfContent);
            logs.add("Generated module: " + moduleName + " with resource " + name + " (op=" + op + ")");
        }

        logs.add("Terraform files generated in memory.");

        try {
            writeToWorkspace();
            logs.add("Files written to workspace: " + workspace);
        } catch (IOException e) {
            logs.add("ERROR writing to workspace: " + e.getMessage());
            throw new RuntimeException(e);
        }

        logs.add("Generation complete.");
    }

    // -----------------------------
    // Write files to workspace
    // -----------------------------

    private void writeToWorkspace() throws IOException {
        Path workspacePath = Paths.get(workspace);

        if (!Files.exists(workspacePath)) {
            Files.createDirectories(workspacePath);
            logs.add("Workspace folder created: " + workspacePath);
        }

        for (var entry : generatedFiles.entrySet()) {
            Path filePath = workspacePath.resolve(entry.getKey());
            Files.createDirectories(filePath.getParent());
            Files.writeString(filePath, entry.getValue(),
                    StandardOpenOption.CREATE,
                    StandardOpenOption.TRUNCATE_EXISTING);
        }
    }

