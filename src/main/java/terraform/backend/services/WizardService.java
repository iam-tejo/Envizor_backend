    // -----------------------------
    // Normalization for STANDARD objects
    // -----------------------------

    private String normalize(String type) {
        String key = type.trim().toLowerCase().replace(" ", "").replace("_", "").replace("-", "");
        return TYPE_MAP.getOrDefault(key, key);
    }

    // -----------------------------
    // STANDARD resource generation
    // -----------------------------

    private String generateStandardResource(String type, String name, Map<String, String> attrs) {
        String key = normalize(type);
        String attributesBlock = renderAttributes(attrs);

        Map<String, String> vars = new HashMap<>();
        vars.put("res", name);
        vars.put("attributes", attributesBlock);

        return switch (key) {
            case "accounts" -> render(ACCOUNT_TEMPLATE, vars);
            case "entitlements" -> render(ENTITLEMENT_TEMPLATE, vars);
            case "roles" -> render(ROLE_TEMPLATE, vars);
            case "endpoints" -> render(ENDPOINT_TEMPLATE, vars);
            case "applications" -> render(APPLICATION_TEMPLATE, vars);
            case "user_groups" -> render(USERGROUP_TEMPLATE, vars);
            case "security_systems" -> render(SECURITY_SYSTEM_TEMPLATE, vars);
            case "schedule_jobs" -> render(SCHEDULE_JOB_TEMPLATE, vars);
            default -> "// Unsupported STANDARD object type: " + type;
        };
    }

    // -----------------------------
    // IMPORT resource generation (ZIP-based)
    // -----------------------------

    private String generateImportResource(String type, String name, String zipFileName) {
        String key = type.trim().toLowerCase();

        Map<String, String> vars = new HashMap<>();
        vars.put("name", name);
        vars.put("zip", zipFileName);

        return switch (key) {
            case "emailtemplate", "email_template" -> render(EMAIL_TEMPLATE_IMPORT, vars);
            case "analytics" -> render(ANALYTICS_IMPORT, vars);
            case "savrole", "sav_role" -> render(SAV_ROLE_IMPORT, vars);
            case "technicalrule", "technical_rule" -> render(TECHNICAL_RULE_IMPORT, vars);
            default -> "// Unsupported IMPORT object type: " + type;
        };
    }

    // -----------------------------
